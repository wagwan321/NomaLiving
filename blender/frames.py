"""Turn rendered PNG frames into the web image sequences used by the scroll walk-through.

Usage (from the project root):
    python blender/frames.py night   blender/render_v3_night        # landscape 1920×1080
    python blender/frames.py day     blender/render_v3_day
    python blender/frames.py night-p blender/render_portrait_night  # portrait 1080×1920
    python blender/frames.py day-p   blender/render_portrait_day

Frames come from blender/render_timeline.py / render_portrait.py (f_0000.png …, numbered by
their position in blender/timeline.json). Each set is written at three quality levels so every
device gets what it needs:
    assets/cine/<set>/      full     (1920 wide, or 1080 for portrait)
    assets/cine/<set>-md/   medium   (2/3 size)
    assets/cine/<set>-sm/   light    (1/2 size)
It also writes assets/js/cine-timeline.js: where each frame sits along the scroll, so the camera
moves at an even pace (fast moves get more scroll distance).
"""
import json
import os
import shutil
import sys
from concurrent.futures import ProcessPoolExecutor

from PIL import Image

TIERS = {"": (1.0, 72, 6), "-md": (2 / 3, 72, 4), "-sm": (0.5, 70, 4)}   # scale, quality, effort


def export(job):
    src, n, outs = job
    im = Image.open(os.path.join(src, f"f_{n:04d}.png")).convert("RGB")
    for out, (scale, q, effort) in outs:
        frame = im if scale == 1.0 else im.resize((round(im.width * scale), round(im.height * scale)), Image.LANCZOS)
        frame.save(os.path.join(out, f"{n:03d}.webp"), "WEBP", quality=q, method=effort)
    return n


if __name__ == "__main__":
    name, src = sys.argv[1], sys.argv[2]
    nums = sorted(int(f[2:6]) for f in os.listdir(src) if f.startswith("f_") and f.endswith(".png"))
    outs = []
    for suffix, spec in TIERS.items():
        out = os.path.join("assets", "cine", name + suffix)
        shutil.rmtree(out, ignore_errors=True)
        os.makedirs(out)
        outs.append((out, spec))
    with ProcessPoolExecutor(max_workers=max(1, (os.cpu_count() or 2) - 1)) as pool:
        list(pool.map(export, [(src, n, outs) for n in nums], chunksize=8))
    for out, _ in outs:
        total = sum(os.path.getsize(os.path.join(out, f)) for f in os.listdir(out))
        w, h = Image.open(os.path.join(out, os.listdir(out)[0])).size
        print(f"{out}: {len(nums)} frames {w}x{h}, {total / 1e6:.1f} MB")

    # even-pace scroll positions (0…1) for every frame, from the motion measured between frames
    tl = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "timeline.json")))
    cum = [0.0]
    for v in tl["weights"]:
        cum.append(cum[-1] + v)
    cum = [round(c / cum[-1], 5) for c in cum]
    with open(os.path.join("assets", "js", "cine-timeline.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write("/* generated by blender/frames.py: scroll position (0-1) of each walk-through frame */\n")
        f.write(f"window.NOMA_TIMELINE = {json.dumps(cum, separators=(',', ':'))};\n")
        # autoplay pace (blender/autoplay_pace.py): turns stretched so the camera never whips round
        pace_file = os.path.join(os.path.dirname(os.path.abspath(__file__)), "autoplay.json")
        if os.path.exists(pace_file):
            pace = json.load(open(pace_file))
            f.write(f"window.NOMA_PACE = {json.dumps(pace['pace'], separators=(',', ':'))};\n")
            f.write(f"window.NOMA_PACE_SECONDS = {pace['seconds']};\n")
