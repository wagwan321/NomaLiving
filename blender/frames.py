"""Turn rendered PNG frames into the web image sequence used by the scroll walk-through.

Usage (from the project root):
    python blender/frames.py night blender/render_v3_night
    python blender/frames.py day   blender/render_v3_day

Frames come from blender/render_timeline.py (f_0000.png … one per entry of
blender/timeline.json) and are written as assets/cine/<mode>/000.webp … at the full render
size. It also writes assets/js/cine-timeline.js: where each frame sits along the scroll,
so the camera moves at an even pace (fast moves get more scroll distance).
Phones load every second frame; the page blends between frames.
"""
import json
import os
import shutil
import sys

from PIL import Image

mode, src = sys.argv[1], sys.argv[2]
nums = sorted(int(f[2:6]) for f in os.listdir(src) if f.startswith("f_") and f.endswith(".png"))

out = os.path.join("assets", "cine", mode)
shutil.rmtree(out, ignore_errors=True)
os.makedirs(out)
for n in nums:
    im = Image.open(os.path.join(src, f"f_{n:04d}.png")).convert("RGB")
    im.save(os.path.join(out, f"{n:03d}.webp"), "WEBP", quality=82, method=6)
total = sum(os.path.getsize(os.path.join(out, f)) for f in os.listdir(out))
print(f"{mode}: {len(nums)} frames at {im.size[0]}x{im.size[1]}, {total / 1e6:.1f} MB")

# even-pace scroll positions (0…1) for every frame, from the motion measured between frames
tl = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "timeline.json")))
cum = [0.0]
for v in tl["weights"]:
    cum.append(cum[-1] + v)
cum = [round(c / cum[-1], 5) for c in cum]
with open(os.path.join("assets", "js", "cine-timeline.js"), "w", encoding="utf-8", newline="\n") as f:
    f.write("/* generated by blender/frames.py: scroll position (0-1) of each walk-through frame */\n")
    f.write(f"window.NOMA_TIMELINE = {json.dumps(cum, separators=(',', ':'))};\n")
print("timeline:", len(cum), "positions")
